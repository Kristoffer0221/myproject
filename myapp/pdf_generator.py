    # c.drawString(100, 640, f"SEX PARTNERS MALE: {hiv_testing.sex_partner_count_male or 'N/A'}")
    # c.drawString(100, 620, f"SEX PARTNERS FEMALE: {hiv_testing.sex_partner_count_female or 'N/A'}")
    # c.drawString(100, 600, f"SEXUAL ACTIVITY MALE: {'Yes' if hiv_testing.sexual_activity_male else 'No'}")
    # c.drawString(100, 580, f"SEXUAL ACTIVITY FEMALE: {'Yes' if hiv_testing.sexual_activity_female else 'No'}")
    # c.drawString(100, 560, f"ORAL SEX: {'Yes' if hiv_testing.oral else 'No'}")
    # c.drawString(100, 540, f"ANAL INSERTER: {'Yes' if hiv_testing.anal_inserter else 'No'}")
