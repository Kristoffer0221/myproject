# pdf_generator.py
import os
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib.utils import ImageReader
from django.conf import settings

def generate_patient_pdf(patient, hiv_testing):
    """
    Generates a single PDF with patient info on page 1
    and HIV testing info on page 2.
    """
    pdf_path = os.path.join(settings.MEDIA_ROOT, "pdfs", f"combined_{patient.id}.pdf")
    os.makedirs(os.path.dirname(pdf_path), exist_ok=True)
    width, height = letter
    c = canvas.Canvas(pdf_path, pagesize=letter)

    # --- PAGE 1: PATIENT INFORMATION ---
    template_image = os.path.join(settings.MEDIA_ROOT, "forms", "blank.jpg")
    if os.path.exists(template_image):
        form_bg = ImageReader(template_image)
        c.drawImage(form_bg, 0, 0, width=width, height=height)

    c.setFont("Helvetica", 10)
    c.drawString(100, 680, f"NAME: {patient.last_name}, {patient.first_name} {patient.middle_name or ''} {patient.suffix or ''}")
    c.drawString(100, 660, f"PHILHEALTH: {patient.philhealth_number or 'N/A'}")
    c.drawString(100, 640, f"PHILSYS: {patient.philsys_number or 'N/A'}")
    c.drawString(100, 620, f"SEX: {patient.sex}")
    c.drawString(100, 600, f"AGE: {patient.age} ({patient.age_in_months or 'N/A'} months)")
    c.drawString(100, 580, f"GENDER IDENTITY: {patient.gender_identity or 'N/A'}")
    c.drawString(100, 560, f"CIVIL STATUS: {patient.civil_status}")
    c.drawString(100, 540, f"CURRENT RESIDENCE: {patient.current_residence_city}, {patient.current_residence_province}")
    c.drawString(100, 520, f"PERMANENT RESIDENCE: {patient.permanent_residence_city}, {patient.permanent_residence_province}")
    c.drawString(100, 500, f"PLACE OF BIRTH: {patient.place_of_birth_city}, {patient.place_of_birth_province}")
    c.drawString(100, 480, f"NATIONALITY: {'Filipino' if patient.is_filipino else patient.other_nationality or 'N/A'}")
    c.drawString(100, 460, f"LIVING WITH PARTNER: {'Yes' if patient.living_with_partner else 'No'}")
    c.drawString(100, 440, f"CHILDREN: {patient.number_of_children or 0}")
    c.drawString(100, 420, f"PREGNANT: {'Yes' if patient.currently_pregnant else 'No'}")

    # Footer for page 1
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(50, 100, "Generated by Django ReportLab - Patient Information Form")

    # Finish page 1
    c.showPage()

